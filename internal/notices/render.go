package notices

import (
	"fmt"
	"strings"
)

// Formats of the rendered document.
const (
	FormatMarkdown = "markdown"
	FormatText     = "text"
)

// Render writes the document in the given format. The output is
// deterministic: same inputs, same bytes.
func Render(doc *Document, format string) (string, error) {
	switch format {
	case FormatMarkdown, "md", "":
		return renderMarkdown(doc), nil
	case FormatText, "txt":
		return renderText(doc), nil
	}
	return "", fmt.Errorf("unknown notices format %q (markdown, text)", format)
}

func summaryLine(doc *Document) string {
	gaps := doc.GapCount()
	line := fmt.Sprintf("%d shipped components, %d licences", len(doc.Entries), len(doc.Licenses()))
	switch gaps {
	case 0:
		return line + ", no gaps."
	case 1:
		return line + ", 1 component with gaps."
	}
	return line + fmt.Sprintf(", %d components with gaps.", gaps)
}

func entryLabel(e Entry) string { return strings.TrimSpace(e.Name + " " + e.Version) }

func licenseLabel(e Entry) string {
	if e.Chosen != e.License && e.Chosen != "" {
		return fmt.Sprintf("%s (chosen from %s: %s)", e.Chosen, e.License, e.ChoiceReason)
	}
	return e.License
}

func textByID(doc *Document) map[string]Text {
	out := make(map[string]Text, len(doc.Texts))
	for _, text := range doc.Texts {
		out[text.ID] = text
	}
	return out
}

func textTitle(text Text) string {
	license := text.License
	if license == "" {
		license = "unidentified licence"
	}
	return license + " (" + text.ID + ")"
}

// fence returns a code fence longer than any backtick run in the body.
func fence(body string) string {
	longest, run := 0, 0
	for _, r := range body {
		if r == '`' {
			run++
			if run > longest {
				longest = run
			}
			continue
		}
		run = 0
	}
	if longest < 3 {
		return "```"
	}
	return strings.Repeat("`", longest+1)
}

func renderMarkdown(doc *Document) string {
	var b strings.Builder
	texts := textByID(doc)
	b.WriteString("# Third-party notices\n\n")
	fmt.Fprintf(&b, "<!-- Generated by `hibou deps notices` (format %d). Do not edit by hand: regenerate it. -->\n\n", FormatVersion)
	if doc.Detector != "" {
		fmt.Fprintf(&b, "Licence detector: %s.\n\n", doc.Detector)
	}
	b.WriteString(summaryLine(doc) + "\n")

	if doc.GapCount() > 0 {
		b.WriteString("\n## Gaps\n\nThese components are listed below, but their notice is incomplete.\n\n")
		for _, e := range doc.Entries {
			for _, gap := range e.Gaps {
				fmt.Fprintf(&b, "- `%s`: %s. Fix: %s.\n", entryLabel(e), gap.Message, gap.Fix)
			}
		}
	}

	if len(doc.Obligations) > 0 {
		b.WriteString("\n## Obligations beyond attribution\n\nThese licences require more than this file. A person must act on each; nothing here fulfils them.\n\n")
		for _, o := range doc.Obligations {
			fmt.Fprintf(&b, "- **%s**: %s. Components: %s.\n", o.License, o.Duty, strings.Join(o.Components, ", "))
		}
	}

	b.WriteString("\n## Components\n")
	for _, e := range doc.Entries {
		fmt.Fprintf(&b, "\n### %s\n\n", entryLabel(e))
		fmt.Fprintf(&b, "- Package: `%s`\n", e.Purl)
		fmt.Fprintf(&b, "- Licence: %s\n", licenseLabel(e))
		for _, line := range e.Copyrights {
			fmt.Fprintf(&b, "- %s\n", line)
		}
		for _, id := range e.TextIDs {
			fmt.Fprintf(&b, "- Licence text: %s\n", textTitle(texts[id]))
		}
		if e.Notice != "" {
			b.WriteString("- NOTICE: see \"NOTICE files\" below\n")
		}
		if e.Source == SourceOverride {
			fmt.Fprintf(&b, "- Evidence: override in .hibou.yaml (%s)\n", e.OverrideReason)
		}
		for _, gap := range e.Gaps {
			fmt.Fprintf(&b, "- Gap: %s\n", gap.Message)
		}
	}

	if len(doc.Texts) > 0 {
		b.WriteString("\n## Licence texts\n")
		for _, text := range doc.Texts {
			f := fence(text.Body)
			fmt.Fprintf(&b, "\n### %s\n\nUsed by: %s.\n\n%s\n%s\n%s\n", textTitle(text), strings.Join(text.UsedBy, ", "), f, text.Body, f)
		}
	}

	wroteNotices := false
	for _, e := range doc.Entries {
		if e.Notice == "" {
			continue
		}
		if !wroteNotices {
			b.WriteString("\n## NOTICE files\n")
			wroteNotices = true
		}
		f := fence(e.Notice)
		fmt.Fprintf(&b, "\n### %s\n\n%s\n%s\n%s\n", entryLabel(e), f, e.Notice, f)
	}

	for _, included := range doc.Included {
		body := strings.TrimSpace(included.Body)
		if body == "" {
			continue
		}
		fmt.Fprintf(&b, "\n## Additional notices (%s)\n\n%s\n", included.Path, body)
	}
	return b.String()
}

const textRule = "------------------------------------------------------------------------"

func renderText(doc *Document) string {
	var b strings.Builder
	texts := textByID(doc)
	b.WriteString("THIRD-PARTY NOTICES\n\n")
	fmt.Fprintf(&b, "Generated by `hibou deps notices` (format %d). Do not edit by hand.\n", FormatVersion)
	if doc.Detector != "" {
		fmt.Fprintf(&b, "Licence detector: %s.\n", doc.Detector)
	}
	b.WriteString(summaryLine(doc) + "\n")

	if doc.GapCount() > 0 {
		b.WriteString("\n" + textRule + "\nGAPS\n" + textRule + "\n\n")
		for _, e := range doc.Entries {
			for _, gap := range e.Gaps {
				fmt.Fprintf(&b, "%s: %s. Fix: %s.\n", entryLabel(e), gap.Message, gap.Fix)
			}
		}
	}
	if len(doc.Obligations) > 0 {
		b.WriteString("\n" + textRule + "\nOBLIGATIONS BEYOND ATTRIBUTION\n" + textRule + "\n\n")
		for _, o := range doc.Obligations {
			fmt.Fprintf(&b, "%s: %s.\n  Components: %s.\n", o.License, o.Duty, strings.Join(o.Components, ", "))
		}
	}

	b.WriteString("\n" + textRule + "\nCOMPONENTS\n" + textRule + "\n")
	for _, e := range doc.Entries {
		fmt.Fprintf(&b, "\n%s\n", entryLabel(e))
		fmt.Fprintf(&b, "  Package: %s\n", e.Purl)
		fmt.Fprintf(&b, "  Licence: %s\n", licenseLabel(e))
		for _, line := range e.Copyrights {
			fmt.Fprintf(&b, "  %s\n", line)
		}
		for _, id := range e.TextIDs {
			fmt.Fprintf(&b, "  Licence text: %s\n", textTitle(texts[id]))
		}
		if e.Notice != "" {
			b.WriteString("  NOTICE: see NOTICE FILES below\n")
		}
		if e.Source == SourceOverride {
			fmt.Fprintf(&b, "  Evidence: override in .hibou.yaml (%s)\n", e.OverrideReason)
		}
		for _, gap := range e.Gaps {
			fmt.Fprintf(&b, "  Gap: %s\n", gap.Message)
		}
	}

	if len(doc.Texts) > 0 {
		b.WriteString("\n" + textRule + "\nLICENCE TEXTS\n" + textRule + "\n")
		for _, text := range doc.Texts {
			fmt.Fprintf(&b, "\n%s\nUsed by: %s.\n\n%s\n\n%s\n", textTitle(text), strings.Join(text.UsedBy, ", "), text.Body, textRule)
		}
	}
	wroteNotices := false
	for _, e := range doc.Entries {
		if e.Notice == "" {
			continue
		}
		if !wroteNotices {
			b.WriteString("\n" + textRule + "\nNOTICE FILES\n" + textRule + "\n")
			wroteNotices = true
		}
		fmt.Fprintf(&b, "\n%s\n\n%s\n\n%s\n", entryLabel(e), e.Notice, textRule)
	}
	for _, included := range doc.Included {
		body := strings.TrimSpace(included.Body)
		if body == "" {
			continue
		}
		fmt.Fprintf(&b, "\n%s\nADDITIONAL NOTICES (%s)\n%s\n\n%s\n", textRule, included.Path, textRule, body)
	}
	return b.String()
}
